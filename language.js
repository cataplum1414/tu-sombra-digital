let currentLanguage = 'es';

export function getLanguage() {
  return currentLanguage;
}

export function text(es, en) {
  return currentLanguage === 'en' ? en : es;
}

export function setLanguage(language) {
  currentLanguage = language === 'en' ? 'en' : 'es';
  const index = currentLanguage === 'en' ? 1 : 0;
  document.documentElement.lang = currentLanguage;
  window.dispatchEvent(new CustomEvent('site-languagewillchange', { detail: { language: currentLanguage } }));

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = copy[element.dataset.i18n]?.[index];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = copy[element.dataset.i18nHtml]?.[index];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const value = copy[element.dataset.i18nAria]?.[index];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });

  document.title = currentLanguage === 'en'
    ? 'Your Digital Shadow — Article 12'
    : 'Tu sombra digital — Artículo 12';
  document.querySelector('meta[name="description"]').content = currentLanguage === 'en'
    ? 'An interactive suspense story set in Alcalá de Henares about Article 12 and the right to privacy.'
    : 'Una historia interactiva de suspense en Alcalá de Henares sobre el artículo 12 y el derecho a la intimidad.';
  const declarationLink = document.querySelector('#un-declaration-link');
  if (declarationLink) declarationLink.href = currentLanguage === 'en'
    ? 'https://www.un.org/en/about-us/universal-declaration-of-human-rights'
    : 'https://www.un.org/es/about-us/universal-declaration-of-human-rights';

  const toggle = document.querySelector('#language-toggle');
  if (toggle) {
    toggle.textContent = currentLanguage === 'en' ? 'ES' : 'EN';
    toggle.setAttribute('aria-label', copy.langToggle[index]);
    toggle.setAttribute('aria-pressed', String(currentLanguage === 'en'));
  }

  window.dispatchEvent(new CustomEvent('site-languagechange', { detail: { language: currentLanguage } }));
}

export function t(key, values = {}) {
  let value = copy[key]?.[currentLanguage === 'en' ? 1 : 0] ?? key;
  for (const [name, replacement] of Object.entries(values)) {
    value = value.replace(`{${name}}`, String(replacement));
  }
  return value;
}
